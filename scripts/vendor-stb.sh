#!/usr/bin/env bash
# Re-vendor native/vendor/stb_image.h and stb_image_write.h exactly as Fedora
# ships them: nothings/stb at Fedora's pinned commit plus every patch in
# Fedora's stb.spec, in order. Upstream has left the GHSL-2023 fixes
# unmerged since 2023; the distros carry them.
#
#   scripts/vendor-stb.sh            (writes native/vendor/ + PROVENANCE.md)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SPEC_URL="https://src.fedoraproject.org/rpms/stb/raw/rawhide/f/stb.spec"
RAW="https://src.fedoraproject.org/rpms/stb/raw/rawhide/f"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

curl -fsSL "$SPEC_URL" -o "$WORK/stb.spec"
COMMIT="$(sed -nE 's/^%global commit ([0-9a-f]{40})/\1/p' "$WORK/stb.spec" | head -1)"
[[ -n "$COMMIT" ]] || { echo "no commit in spec" >&2; exit 1; }

git -C "$WORK" init -q stb
git -C "$WORK/stb" fetch -q --depth 1 https://github.com/nothings/stb "$COMMIT"
git -C "$WORK/stb" checkout -q FETCH_HEAD

applied=()
while read -r patch; do
  case "$patch" in
    http*|%*) url="$(printf '%s' "$patch" | sed 's|^%{url}|https://github.com/nothings/stb|')" ;;
    *) url="$RAW/$patch" ;;
  esac
  file="$WORK/$(basename "$url")"
  curl -fsSL "$url" -o "$file"
  # Only the image headers matter here; other headers' hunks are skipped.
  if git -C "$WORK/stb" apply --check --include=stb_image.h --include=stb_image_write.h "$file" 2>/dev/null; then
    git -C "$WORK/stb" apply --include=stb_image.h --include=stb_image_write.h "$file"
    applied+=("$patch")
  else
    echo "note: $patch does not apply to the image headers (or touches none)" >&2
  fi
done < <(sed -nE 's/^Patch[0-9]*:[[:space:]]+(.*)$/\1/p' "$WORK/stb.spec")

cp "$WORK/stb/stb_image.h" "$WORK/stb/stb_image_write.h" "$ROOT/native/vendor/"
{
  echo "# native/vendor/"
  echo
  echo "Generated by \`scripts/vendor-stb.sh\` — do not edit."
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| Upstream | https://github.com/nothings/stb @ \`$COMMIT\` (Fedora's pin) |"
  echo "| Patch set | Fedora \`stb.spec\` ($SPEC_URL), applied in order |"
  echo "| License | stb: public domain / MIT (dual) |"
  echo
  echo "Patches touching the image headers:"
  echo
  for p in "${applied[@]}"; do echo "- \`$p\`"; done
  echo
  echo "SHA-256:"
  echo
  echo '```'
  (cd "$ROOT/native/vendor" && shasum -a 256 stb_image.h stb_image_write.h)
  echo '```'
} > "$ROOT/native/vendor/PROVENANCE.md"
echo "vendored stb $COMMIT with ${#applied[@]} patches"
